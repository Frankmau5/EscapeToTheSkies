using Microsoft.Xna.Framework;
using Microsoft.Xna.Framework.Graphics;

namespace EscapeToTheSkies;

public sealed class BitmapFont : IDisposable
{
    private const int GlyphW = 5;
    private const int GlyphH = 7;
    private const int CellW = 6;
    private const int CellH = 8;
    private const int Columns = 16;
    private const int FirstChar = 32;
    private const int LastChar = 126;

    private readonly Texture2D _atlas;
    private readonly Texture2D _pixel;

    public BitmapFont(GraphicsDevice graphicsDevice)
    {
        _pixel = new Texture2D(graphicsDevice, 1, 1);
        _pixel.SetData(new[] { Color.White });

        int rows = ((LastChar - FirstChar + 1) + Columns - 1) / Columns;
        int texW = Columns * CellW;
        int texH = rows * CellH;
        var data = new Color[texW * texH];

        for (int ch = FirstChar; ch <= LastChar; ch++)
        {
            byte[] glyph = GetGlyph((char)ch);
            int idx = ch - FirstChar;
            int gx = (idx % Columns) * CellW;
            int gy = (idx / Columns) * CellH;

            for (int row = 0; row < GlyphH; row++)
            {
                byte bits = glyph[row];
                for (int col = 0; col < GlyphW; col++)
                {
                    if ((bits & (1 << (GlyphW - 1 - col))) != 0)
                    {
                        data[(gy + row) * texW + (gx + col)] = Color.White;
                    }
                }
            }
        }

        _atlas = new Texture2D(graphicsDevice, texW, texH);
        _atlas.SetData(data);
    }

    public int LineHeight(int scale = 2) => GlyphH * scale;

    public Vector2 MeasureString(string text, int scale = 2)
    {
        if (string.IsNullOrEmpty(text))
        {
            return Vector2.Zero;
        }

        int maxCols = 0;
        int curCols = 0;
        int lines = 1;

        foreach (char c in text)
        {
            if (c == '\n')
            {
                maxCols = Math.Max(maxCols, curCols);
                curCols = 0;
                lines++;
            }
            else
            {
                curCols++;
            }
        }

        maxCols = Math.Max(maxCols, curCols);
        return new Vector2(
            Math.Max(0, maxCols * CellW - 1) * scale,
            (lines * CellH - 1) * scale
        );
    }

    public void DrawString(SpriteBatch sb, string text, Vector2 pos, Color color, int scale = 2, bool shadow = true)
    {
        if (string.IsNullOrEmpty(text))
        {
            return;
        }

        if (shadow)
        {
            DrawRaw(sb, text, pos + new Vector2(scale, scale), new Color(10, 10, 18, (byte)(color.A * 0.78f)), scale);
        }

        DrawRaw(sb, text, pos, color, scale);
    }

    public void DrawCentered(SpriteBatch sb, string text, float centerX, float y, Color color, int scale = 2, bool shadow = true)
    {
        Vector2 size = MeasureString(text, scale);
        DrawString(sb, text, new Vector2(MathF.Round(centerX - size.X * 0.5f), MathF.Round(y)), color, scale, shadow);
    }

    public void DrawDeckBadge(SpriteBatch sb, string label, Vector2 pos, Color badgeColor, int scale = 2)
    {
        Vector2 textSize = MeasureString(label, scale);
        int padX = 5 * scale;
        int padY = 2 * scale;
        int w = (int)textSize.X + padX * 2;
        int h = (int)textSize.Y + padY * 2;

        // Outer border + dark fill + colored highlight
        sb.Draw(_pixel, new Rectangle((int)pos.X, (int)pos.Y, w, h), new Color(16, 18, 28, 235));
        sb.Draw(_pixel, new Rectangle((int)pos.X, (int)pos.Y, w, scale), badgeColor);
        sb.Draw(_pixel, new Rectangle((int)pos.X, (int)pos.Y + h - scale, w, scale), badgeColor * 0.8f);
        sb.Draw(_pixel, new Rectangle((int)pos.X, (int)pos.Y, scale, h), badgeColor * 0.85f);
        sb.Draw(_pixel, new Rectangle((int)pos.X + w - scale, (int)pos.Y, scale, h), badgeColor * 0.85f);

        DrawString(sb, label, pos + new Vector2(padX, padY), badgeColor, scale, shadow: true);
    }

    public int MeasureBadgeWidth(string label, int scale = 2)
    {
        Vector2 textSize = MeasureString(label, scale);
        return (int)textSize.X + 10 * scale;
    }

    private void DrawRaw(SpriteBatch sb, string text, Vector2 pos, Color color, int scale)
    {
        float x = pos.X;
        float y = pos.Y;

        foreach (char raw in text)
        {
            if (raw == '\n')
            {
                x = pos.X;
                y += CellH * scale;
                continue;
            }

            char c = raw;
            if (c < FirstChar || c > LastChar)
            {
                c = '?';
            }

            int idx = c - FirstChar;
            var src = new Rectangle((idx % Columns) * CellW, (idx / Columns) * CellH, GlyphW, GlyphH);
            var dst = new Rectangle((int)x, (int)y, GlyphW * scale, GlyphH * scale);
            sb.Draw(_atlas, dst, src, color);
            x += CellW * scale;
        }
    }

